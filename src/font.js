const ALIAS = { '＋': '+', '’': "'", '‘': "'", '“': '"', '”': '"', '–': '-', ' ': ' ' };

function fromRows(rows) {
  const cols = [0, 0, 0, 0, 0];
  rows.forEach((r, y) => {
    for (let x = 0; x < 5; x++) if (r[x] === '#') cols[x] |= 1 << y;
  });
  return cols;
}

const cache = new Map();
const BOX = fromRows(['#####', '#...#', '#...#', '#...#', '#...#', '#...#', '#####', '.....']);

// The 5 column bytes for a character, or 'top' / 'mid' for the lines drawn across the whole cell.
export function glyph(ch) {
  let g = cache.get(ch);
  if (g) return g;
  const code = ch.codePointAt(0);
  const a = ALIAS[ch];
  if (a) g = glyph(a);
  else if (code >= 32 && code <= 126) g = ASCII[code - 32];
  else if (SYMBOLS[ch]) g = typeof SYMBOLS[ch] === 'string' ? SYMBOLS[ch] : fromRows(SYMBOLS[ch]);
  else {
    const base = ch.normalize('NFD')[0];
    g = base && base !== ch && base.codePointAt(0) < 127 ? glyph(base) : BOX;
  }
  cache.set(ch, g);
  return g;
}
export const hasGlyph = (ch) => {
  const code = ch.codePointAt(0);
  return (code >= 32 && code <= 126) || !!SYMBOLS[ch] || !!ALIAS[ch];
};
